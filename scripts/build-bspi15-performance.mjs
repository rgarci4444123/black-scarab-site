import fs from 'node:fs/promises';
import path from 'node:path';
import {calculatePerformance} from './bspi15-calculations.mjs';
const root=process.cwd();
const csv=await fs.readFile(path.join(root,'data/bspi15/daily-closes.csv'),'utf8');
const lines=csv.trim().split(/\r?\n/),headers=lines.shift().split(',');
const rows=lines.map(line=>Object.fromEntries(line.split(',').map((value,k)=>[headers[k],k?Number(value):value])));
const splits=JSON.parse(await fs.readFile(path.join(root,'data/bspi15/splits.json'),'utf8'));
const {observations}=calculatePerformance(rows,splits);
await fs.writeFile(path.join(root,'public/data/bspi15-performance.json'),JSON.stringify(observations,null,2)+'\n');
console.log(`Built ${observations.length} BSPI15 performance observations.`);
