export type IndustrySlug = keyof typeof industryRegistry;
export type TechnologySlug = keyof typeof technologyRegistry;
export type ApplicationSlug = keyof typeof applicationRegistry;

export type ArticleTaxonomy = {
  primaryIndustry: IndustrySlug;
  relevantIndustries?: readonly IndustrySlug[];
  technologies: readonly TechnologySlug[];
  applications: readonly ApplicationSlug[];
};

const hasOwn = (registry: object, value: unknown): value is string =>
  typeof value === "string" && Object.prototype.hasOwnProperty.call(registry, value);

/** Reject unknown terms and incomplete content instead of silently classifying it. */
export function assertArticleTaxonomy(
  value: unknown,
  context = "Article",
): asserts value is ArticleTaxonomy {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${context}: taxonomy is required`);
  }
  const taxonomy = value as Record<string, unknown>;
  const allowed = new Set(["primaryIndustry", "relevantIndustries", "technologies", "applications"]);
  if (Object.keys(taxonomy).some((key) => !allowed.has(key))) {
    throw new Error(`${context}: unknown taxonomy field`);
  }
  if (!hasOwn(industryRegistry, taxonomy.primaryIndustry)) {
    throw new Error(`${context}: invalid primaryIndustry`);
  }
  const fields = [
    ["relevantIndustries", industryRegistry],
    ["technologies", technologyRegistry],
    ["applications", applicationRegistry],
  ] as const;
  for (const [field, registry] of fields) {
    const terms = taxonomy[field];
    if (field === "relevantIndustries" && terms === undefined) continue;
    if (!Array.isArray(terms) || terms.some((term) => !hasOwn(registry, term))) {
      throw new Error(`${context}: invalid ${field}`);
    }
    if (new Set(terms).size !== terms.length) {
      throw new Error(`${context}: duplicate ${field}`);
    }
  }
  if ((taxonomy.relevantIndustries as string[] | undefined)?.includes(taxonomy.primaryIndustry as string)) {
    throw new Error(`${context}: primaryIndustry repeated in relevantIndustries`);
  }
}

export type TaxonomyFacets = {
  industries?: readonly IndustrySlug[];
  technologies?: readonly TechnologySlug[];
  applications?: readonly ApplicationSlug[];
};

/** OR within one facet; AND across facets. Cross-Industry is never a wildcard. */
export function matchesArticleTaxonomy(taxonomy: ArticleTaxonomy, facets: TaxonomyFacets): boolean {
  const industries = [taxonomy.primaryIndustry, ...(taxonomy.relevantIndustries ?? [])];
  return (
    (!facets.industries?.length || facets.industries.some((term) => industries.includes(term))) &&
    (!facets.technologies?.length || facets.technologies.some((term) => taxonomy.technologies.includes(term))) &&
    (!facets.applications?.length || facets.applications.some((term) => taxonomy.applications.includes(term)))
  );
}

export type PublicationFacets = TaxonomyFacets & {
  /** Inclusive ISO date or timestamp bounds. Date-only bounds cover the entire UTC day. */
  publishedFrom?: string;
  publishedThrough?: string;
};

function dateBound(value: string | undefined, endOfDay: boolean): number | undefined {
  if (value === undefined) return undefined;
  const timestamp = Date.parse(/^\d{4}-\d{2}-\d{2}$/.test(value)
    ? `${value}T${endOfDay ? "23:59:59.999" : "00:00:00.000"}Z`
    : value);
  if (!Number.isFinite(timestamp)) throw new Error(`Invalid publication date: ${value}`);
  return timestamp;
}

/** Preserve source order, objects and relationships; undated external records skip date queries. */
export function filterPublications<T extends {
  taxonomy: ArticleTaxonomy;
  publishedAt?: string;
  publishedDate?: string;
}>(publications: readonly T[], facets: PublicationFacets = {}): T[] {
  const from = dateBound(facets.publishedFrom, false);
  const through = dateBound(facets.publishedThrough, true);
  if (from !== undefined && through !== undefined && from > through) {
    throw new Error("Publication date range is reversed");
  }
  return publications.filter((article) => {
    if (!matchesArticleTaxonomy(article.taxonomy, facets)) return false;
    if (from === undefined && through === undefined) return true;
    const date = dateBound(article.publishedAt ?? article.publishedDate, false);
    return date !== undefined && (from === undefined || date >= from) && (through === undefined || date <= through);
  });
}

/** A future route identity only. Archive availability is controlled separately. */
export function industryArchivePath(slug: IndustrySlug): `/industry/${IndustrySlug}` {
  return `/industry/${slug}`;
}

/** Generate export schemas from the authoritative registries rather than duplicate vocabularies. */
export function articleTaxonomySchema() {
  const terms = (registry: object) => ({ type: "string", enum: Object.keys(registry) });
  const list = (registry: object) => ({ type: "array", uniqueItems: true, items: terms(registry) });
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    title: "Black Scarab article taxonomy",
    type: "object",
    additionalProperties: false,
    required: ["primaryIndustry", "technologies", "applications"],
    properties: {
      primaryIndustry: terms(industryRegistry),
      relevantIndustries: list(industryRegistry),
      technologies: list(technologyRegistry),
      applications: list(applicationRegistry),
    },
  };
}
